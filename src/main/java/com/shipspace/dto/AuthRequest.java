package com.shipspace.dto;


import jakarta.validation.constraints.NotBlank;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

/**
 * DTO for authentication requests.
 * Used for GitHub OAuth code exchange.
 *
 * The `state` field is required to prevent OAuth CSRF attacks.
 * The client must generate a random state, include it in the GitHub
 * authorization URL, and send it back here for server-side validation.
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class AuthRequest {

    /**
     * GitHub OAuth authorization code.
     */
    @NotBlank(message = "OAuth code is required")
    private String code;

    /**
     * CSRF state token generated by the server via GET /api/auth/state.
     * Must match the value stored in Redis for this session.
     */
    @NotBlank(message = "OAuth state is required")
    private String state;
}
